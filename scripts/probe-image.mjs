import { readFile } from "node:fs/promises";
import * as pdfjs from "pdfjs-dist/legacy/build/pdf.mjs";
import sharp from "sharp";
const data = new Uint8Array(await readFile(process.argv[2]));
const doc = await pdfjs.getDocument({ data, isEvalSupported: false, useSystemFonts: false }).promise;
const page = await doc.getPage(6);
const tc = await page.getTextContent();
console.log("text items", tc.items.length);
const ops = await page.getOperatorList();
const imgs = [];
ops.fnArray.forEach((fn, i) => { if (fn === pdfjs.OPS.paintImageXObject) imgs.push(ops.argsArray[i]); });
console.log("image ops", imgs.length, imgs.map(a => a.slice(0,3)));
const name = imgs[0][0];
const img = await new Promise(r => page.objs.get(name, r));
console.log("img keys", Object.keys(img), img.width, img.height, img.kind, img.data?.length, img.bitmap && "bitmap");
const ch = img.data.length / (img.width * img.height);
const buf = await sharp(Buffer.from(img.data), { raw: { width: img.width, height: img.height, channels: ch } }).png().toBuffer();
console.log("png bytes", buf.length);
await sharp(buf).extract({ left: 0, top: 0, width: 1000, height: 1000 }).png().toFile(process.argv[3]);

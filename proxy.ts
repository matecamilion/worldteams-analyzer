import { createServerClient } from "@supabase/ssr";
import { NextResponse, type NextRequest } from "next/server";

/**
 * Refresca la sesión de Supabase en cada request (los Server Components no pueden escribir
 * cookies). No autoriza nada: el control real está en lib/guard.ts, en cada página y API.
 */
export async function proxy(request: NextRequest) {
  let response = NextResponse.next({ request });
  const supabase = createServerClient(process.env.NEXT_PUBLIC_SUPABASE_URL!, process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY!, {
    cookies: {
      getAll: () => request.cookies.getAll(),
      setAll: (list) => {
        for (const { name, value } of list) request.cookies.set(name, value);
        response = NextResponse.next({ request });
        for (const { name, value, options } of list) response.cookies.set(name, value, options);
      },
    },
  });
  await supabase.auth.getUser();
  return response;
}

export const config = {
  // Todo menos archivos estáticos, el worker de PDF, el plano de ejemplo y el callback de OAuth.
  matcher: ["/((?!_next/static|_next/image|favicon.ico|pdf.worker.min.mjs|ejemplo/|logo-|auth/callback).*)"],
};
